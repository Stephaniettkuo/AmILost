// Turns data/cs-calendar.ics into src/data/calendarSnapshot.ts, because the app's bundler can't
// import .ics files. Run it after downloading a fresh copy of the feed:
//   node scripts/snapshot-calendar.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const text = readFileSync('data/cs-calendar.ics', 'utf8').replace(/\r\n/g, '\n');
// Put the text inside a template string: escape backslashes, backticks and ${ so it stays exactly as it was.
const escaped = text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
writeFileSync(
  'src/data/calendarSnapshot.ts',
  `// GENERATED by scripts/snapshot-calendar.mjs from data/cs-calendar.ics. Do not edit by hand.\nexport default \`${escaped}\`;\n`,
);
console.log(`Wrote src/data/calendarSnapshot.ts (${text.split('\n').length} lines)`);
